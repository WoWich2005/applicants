-- Подменяет имена абитуриентов (applicants.name) на правдоподобные ФИО.
-- Формат: «Фамилия Имя Отчество», русско-белорусские имена.
-- Пол выбирается случайно; фамилия, имя и отчество согласованы по полу
-- (женские фамилии -ова/-ская, женские отчества -овна/-евна).
--
-- На name нет UNIQUE-ограничения, поэтому повторы допустимы (как в реальности).
--
-- ВНИМАНИЕ: операция необратима без бэкапа. Восстановление:
--   docker exec -i bntuapplicants-postgres pg_restore -U bntuapplicants -d bntuapplicants --clean --if-exists < backups/<file>.dump

BEGIN;

UPDATE applicants AS a
SET name =
    CASE
        WHEN random() < 0.5 THEN
            d.msurn[1 + floor(random() * array_length(d.msurn, 1))::int] || ' ' ||
            d.mname[1 + floor(random() * array_length(d.mname, 1))::int] || ' ' ||
            d.mpat [1 + floor(random() * array_length(d.mpat , 1))::int]
        ELSE
            d.fsurn[1 + floor(random() * array_length(d.fsurn, 1))::int] || ' ' ||
            d.fname[1 + floor(random() * array_length(d.fname, 1))::int] || ' ' ||
            d.fpat [1 + floor(random() * array_length(d.fpat , 1))::int]
    END
FROM (
    SELECT
        -- Мужские фамилии
        ARRAY['Иванов','Петров','Козлов','Новиков','Морозов','Волков','Соколов',
              'Лебедев','Кузнецов','Васильев','Павлов','Голубев','Богданов','Ковалёв',
              'Зайцев','Дроздов','Луканский','Барановский','Савицкий','Карпович',
              'Наркович','Тарасевич','Гоч','Шайтор','Лобань','Бондарь','Мельник']::text[] AS msurn,
        -- Женские фамилии (согласованы по форме)
        ARRAY['Иванова','Петрова','Козлова','Новикова','Морозова','Волкова','Соколова',
              'Лебедева','Кузнецова','Васильева','Павлова','Голубева','Богданова','Ковалёва',
              'Зайцева','Дроздова','Луканская','Барановская','Савицкая','Карпович',
              'Наркович','Тарасевич','Гоч','Шайтор','Лобань','Бондарь','Мельник']::text[] AS fsurn,
        -- Мужские имена
        ARRAY['Александр','Дмитрий','Сергей','Андрей','Максим','Артём','Иван','Никита',
              'Кирилл','Егор','Илья','Михаил','Владислав','Павел','Антон','Глеб','Роман',
              'Денис','Алексей','Тимофей','Владимир','Георгий','Вадим']::text[] AS mname,
        -- Женские имена
        ARRAY['Анна','Мария','Виктория','Полина','Анастасия','Дарья','Екатерина',
              'Елизавета','Ксения','Алина','Ольга','Юлия','Валерия','София','Татьяна',
              'Маргарита','Вероника','Кристина','Арина','Диана','Ангелина','Надежда']::text[] AS fname,
        -- Мужские отчества
        ARRAY['Иванович','Дмитриевич','Сергеевич','Александрович','Викторович',
              'Михайлович','Андреевич','Николаевич','Алексеевич','Владимирович',
              'Григорьевич','Олегович','Павлович','Юрьевич','Евгеньевич','Анатольевич',
              'Васильевич','Петрович','Максимович','Артёмович','Денисович','Игоревич']::text[] AS mpat,
        -- Женские отчества
        ARRAY['Ивановна','Дмитриевна','Сергеевна','Александровна','Викторовна',
              'Михайловна','Андреевна','Николаевна','Алексеевна','Владимировна',
              'Григорьевна','Олеговна','Павловна','Юрьевна','Евгеньевна','Анатольевна',
              'Васильевна','Петровна','Максимовна','Артёмовна','Денисовна','Игоревна']::text[] AS fpat
) d;

DO $$
DECLARE n int;
BEGIN
    SELECT count(*) INTO n FROM applicants;
    RAISE NOTICE 'Имена подменены у % абитуриентов', n;
END $$;

COMMIT;
